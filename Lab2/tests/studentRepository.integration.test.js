/**
 * studentRepository.integration.test.js
 * -----------------------------------------------------------------------
 * Lab 5: Integration tests for studentRepository.js against a REAL
 * PostgreSQL database started by Testcontainers - there is no mocking
 * anywhere in this file.
 *
 * One throwaway PostgreSQL 16 container is started once for this whole
 * test file (beforeAll) and stopped afterwards (afterAll). The
 * `student_records` table is truncated before every individual test
 * (beforeEach) so tests stay independent without paying the cost of a
 * brand-new container per test.
 *
 * Requirements covered (Lab 5, Instruction steps 3 & 6):
 *   - create/register a student
 *   - retrieve a student by ID
 *   - search students
 *   - list all registered students
 *   - update student information
 *   - delete a student record
 *   - duplicate-record handling
 *   - non-existent record handling
 *
 * Running this file requires Docker Desktop (or an equivalent engine) to
 * be installed and running - Testcontainers uses it to pull and start
 * the real postgres:16-alpine image.
 * -----------------------------------------------------------------------
 */
const { Pool } = require('pg');
const { PostgreSqlContainer } = require('@testcontainers/postgresql');
const { StudentRepository, DuplicateStudentError, StudentNotFoundError } = require('../src/repositories/studentRepository');
const { initSchema } = require('../src/db/pool');

jest.setTimeout(120000); // container pull/startup can take a while on first run

let container;
let pool;
let repository;

beforeAll(async () => {
  container = await new PostgreSqlContainer('postgres:16-alpine').start();
  pool = new Pool({ connectionString: container.getConnectionUri() });
  await initSchema(pool);
  repository = new StudentRepository(pool);
});

afterAll(async () => {
  await pool.end();
  await container.stop();
});

beforeEach(async () => {
  await pool.query('TRUNCATE TABLE student_records RESTART IDENTITY');
});

// ======================================================================
// Create (+ duplicate handling)
// ======================================================================
describe('createStudent', () => {
  test('creates a student successfully', async () => {
    const student = await repository.createStudent({
      studentId: '02240365',
      name: 'Sonam Zangmo',
      email: 'sonam@example.com',
      programme: 'BE Software Engineering',
    });
    expect(student.studentId).toBe('02240365');
    expect(student.id).toBeDefined(); // real primary key generated by Postgres
  });

  test('rejects a duplicate Student ID', async () => {
    await repository.createStudent({ studentId: '02240001', name: 'A', email: 'a@example.com', programme: 'BE SE' });
    await expect(
      repository.createStudent({ studentId: '02240001', name: 'B', email: 'b@example.com', programme: 'BE SE' })
    ).rejects.toThrow(DuplicateStudentError);
  });

  test('a duplicate attempt does not overwrite the original record', async () => {
    await repository.createStudent({ studentId: '02240010', name: 'Original', email: 'o@example.com', programme: 'BE SE' });
    await repository
      .createStudent({ studentId: '02240010', name: 'Attempted Overwrite', email: 'x@example.com', programme: 'BE SE' })
      .catch(() => {});
    const stillOriginal = await repository.getStudent('02240010');
    expect(stillOriginal.name).toBe('Original');
  });
});

// ======================================================================
// Read (get / search / list) + non-existent handling
// ======================================================================
describe('getStudent / non-existent handling', () => {
  test('retrieves an existing student', async () => {
    await repository.createStudent({ studentId: '02240002', name: 'Student Two', email: 's2@example.com', programme: 'BE SE' });
    const found = await repository.getStudent('02240002');
    expect(found.name).toBe('Student Two');
  });

  test('returns null for a non-existent student', async () => {
    const found = await repository.getStudent('00000000');
    expect(found).toBeNull();
  });

  test('getStudentOrThrow throws for a non-existent student', async () => {
    await expect(repository.getStudentOrThrow('00000000')).rejects.toThrow(StudentNotFoundError);
  });
});

describe('listStudents / searchStudents', () => {
  test('lists all students', async () => {
    await repository.createStudent({ studentId: '02240003', name: 'Alice', email: 'alice@example.com', programme: 'BE SE' });
    await repository.createStudent({ studentId: '02240004', name: 'Bob', email: 'bob@example.com', programme: 'BE IT' });
    const all = await repository.listStudents();
    const ids = all.map((s) => s.studentId);
    expect(ids).toEqual(expect.arrayContaining(['02240003', '02240004']));
  });

  test('searches by partial name', async () => {
    await repository.createStudent({ studentId: '02240005', name: 'Charlie Wangmo', email: 'c@example.com', programme: 'BE SE' });
    const results = await repository.searchStudents('Wangmo');
    expect(results.some((s) => s.studentId === '02240005')).toBe(true);
  });

  test('searches by partial Student ID', async () => {
    await repository.createStudent({ studentId: '02240006', name: 'Dorji', email: 'd@example.com', programme: 'BE SE' });
    const results = await repository.searchStudents('240006');
    expect(results.some((s) => s.studentId === '02240006')).toBe(true);
  });

  test('returns an empty array when nothing matches', async () => {
    const results = await repository.searchStudents('NoSuchStudentXYZ');
    expect(results).toEqual([]);
  });
});

// ======================================================================
// Update
// ======================================================================
describe('updateStudent', () => {
  test('updates an existing student', async () => {
    await repository.createStudent({ studentId: '02240007', name: 'Old Name', email: 'old@example.com', programme: 'BE SE' });
    const updated = await repository.updateStudent('02240007', { name: 'New Name', email: 'new@example.com' });
    expect(updated.name).toBe('New Name');
    expect(updated.email).toBe('new@example.com');
  });

  test('persists the update (re-fetching reflects the change)', async () => {
    await repository.createStudent({ studentId: '02240011', name: 'Keep Name', email: 'keep@example.com', programme: 'BE SE' });
    await repository.updateStudent('02240011', { programme: 'BE IT' });
    const reloaded = await repository.getStudent('02240011');
    expect(reloaded.name).toBe('Keep Name'); // untouched field stays as-is
    expect(reloaded.programme).toBe('BE IT'); // updated field changed
  });

  test('throws when updating a non-existent student', async () => {
    await expect(repository.updateStudent('00000000', { name: 'Ghost' })).rejects.toThrow(StudentNotFoundError);
  });
});

// ======================================================================
// Delete
// ======================================================================
describe('deleteStudent', () => {
  test('deletes an existing student', async () => {
    await repository.createStudent({ studentId: '02240008', name: 'To Delete', email: 'del@example.com', programme: 'BE SE' });
    await expect(repository.deleteStudent('02240008')).resolves.toBe(true);
    const found = await repository.getStudent('02240008');
    expect(found).toBeNull();
  });

  test('throws when deleting a non-existent student', async () => {
    await expect(repository.deleteStudent('00000000')).rejects.toThrow(StudentNotFoundError);
  });

  test('a deleted Student ID can be recreated', async () => {
    await repository.createStudent({ studentId: '02240009', name: 'Recreate Me', email: 'r@example.com', programme: 'BE SE' });
    await repository.deleteStudent('02240009');
    const recreated = await repository.createStudent({ studentId: '02240009', name: 'Recreated', email: 'r2@example.com', programme: 'BE SE' });
    expect(recreated.name).toBe('Recreated');
  });
});
